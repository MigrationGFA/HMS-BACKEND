-- Master Service Catalog + link domain catalogs.
-- Extends legacy DEPARTMENTS; creates SERVICE_* / MASTER_SERVICES tables.
-- Backfills MasterServices from LAB_TESTS, IMAGING_STUDIES, ADMISSION_BILLING_ITEMS.

-- DEPARTMENTS may be missing on DBs that never applied the legacy init table.
CREATE TABLE IF NOT EXISTS "DEPARTMENTS" (
    "DEPARTMENT_ID" SERIAL NOT NULL,
    "NAME" VARCHAR(255),
    "CODE" VARCHAR(40),
    "STATUS" VARCHAR(30) NOT NULL DEFAULT 'Active',
    "CREATED_BY" VARCHAR(100),
    "CREATED_DATE" TIMESTAMP(3),
    "UPDATED_BY" VARCHAR(100),
    "UPDATED_DATE" TIMESTAMP(3),
    CONSTRAINT "DEPARTMENTS_pkey" PRIMARY KEY ("DEPARTMENT_ID")
);

-- Extend legacy DEPARTMENTS (init only had DEPARTMENT_ID + NAME)
ALTER TABLE "DEPARTMENTS" ADD COLUMN IF NOT EXISTS "CODE" VARCHAR(40);
ALTER TABLE "DEPARTMENTS" ADD COLUMN IF NOT EXISTS "STATUS" VARCHAR(30) NOT NULL DEFAULT 'Active';
ALTER TABLE "DEPARTMENTS" ADD COLUMN IF NOT EXISTS "CREATED_BY" VARCHAR(100);
ALTER TABLE "DEPARTMENTS" ADD COLUMN IF NOT EXISTS "CREATED_DATE" TIMESTAMP(3);
ALTER TABLE "DEPARTMENTS" ADD COLUMN IF NOT EXISTS "UPDATED_BY" VARCHAR(100);
ALTER TABLE "DEPARTMENTS" ADD COLUMN IF NOT EXISTS "UPDATED_DATE" TIMESTAMP(3);

CREATE UNIQUE INDEX IF NOT EXISTS "DEPARTMENTS_CODE_key" ON "DEPARTMENTS"("CODE");
CREATE INDEX IF NOT EXISTS "DEPARTMENTS_STATUS_idx" ON "DEPARTMENTS"("STATUS");
CREATE INDEX IF NOT EXISTS "DEPARTMENTS_NAME_idx" ON "DEPARTMENTS"("NAME");

CREATE TABLE IF NOT EXISTS "SERVICE_CATEGORIES" (
    "CATEGORY_ID" SERIAL NOT NULL,
    "CODE" VARCHAR(40) NOT NULL,
    "NAME" VARCHAR(150) NOT NULL,
    "STATUS" VARCHAR(30) NOT NULL DEFAULT 'Active',
    "CREATED_BY" VARCHAR(100),
    "CREATED_DATE" TIMESTAMP(3),
    "UPDATED_BY" VARCHAR(100),
    "UPDATED_DATE" TIMESTAMP(3),
    CONSTRAINT "SERVICE_CATEGORIES_pkey" PRIMARY KEY ("CATEGORY_ID")
);

CREATE UNIQUE INDEX IF NOT EXISTS "SERVICE_CATEGORIES_CODE_key" ON "SERVICE_CATEGORIES"("CODE");
CREATE INDEX IF NOT EXISTS "SERVICE_CATEGORIES_STATUS_idx" ON "SERVICE_CATEGORIES"("STATUS");

CREATE TABLE IF NOT EXISTS "MASTER_SERVICES" (
    "SERVICE_ID" SERIAL NOT NULL,
