CREATE INDEX IF NOT EXISTS "SERVICE_PAYER_PRICES_SERVICE_ID_idx" ON "SERVICE_PAYER_PRICES"("SERVICE_ID");
CREATE INDEX IF NOT EXISTS "SERVICE_PAYER_PRICES_PAYER_ID_idx" ON "SERVICE_PAYER_PRICES"("PAYER_ID");
