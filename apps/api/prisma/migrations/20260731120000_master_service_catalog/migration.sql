    "STAFF_PRICE" DECIMAL(14,2),
    "ONLINE_BOOKABLE" BOOLEAN NOT NULL DEFAULT false,
    "APPOINTMENT_REQUIRED" BOOLEAN NOT NULL DEFAULT false,
    "REQUIRES_DOCTOR_ORDER" BOOLEAN NOT NULL DEFAULT true,
    "INSURANCE_ELIGIBLE" BOOLEAN NOT NULL DEFAULT true,
    "AGE_RESTRICTION" VARCHAR(100),
    "GENDER_RESTRICTION" VARCHAR(30),
    "STATUS" VARCHAR(40) NOT NULL DEFAULT 'PENDING_PRICING',
    "CREATED_BY_ID" INTEGER,
    "CREATED_BY" VARCHAR(100),
    "CREATED_DATE" TIMESTAMP(3),
    "UPDATED_BY_ID" INTEGER,
    "UPDATED_BY" VARCHAR(100),
    "UPDATED_DATE" TIMESTAMP(3),
    CONSTRAINT "MASTER_SERVICES_pkey" PRIMARY KEY ("SERVICE_ID")
);

CREATE UNIQUE INDEX IF NOT EXISTS "MASTER_SERVICES_SERVICE_CODE_key" ON "MASTER_SERVICES"("SERVICE_CODE");
CREATE INDEX IF NOT EXISTS "MASTER_SERVICES_CATEGORY_ID_idx" ON "MASTER_SERVICES"("CATEGORY_ID");
CREATE INDEX IF NOT EXISTS "MASTER_SERVICES_DEPARTMENT_ID_idx" ON "MASTER_SERVICES"("DEPARTMENT_ID");
