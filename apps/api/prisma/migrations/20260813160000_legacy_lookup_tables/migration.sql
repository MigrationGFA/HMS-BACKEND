ALTER TABLE "WARDS" ADD COLUMN IF NOT EXISTS "DESCRIPTION" VARCHAR(500);
ALTER TABLE "WARDS" ADD COLUMN IF NOT EXISTS "HOSPITAL_ID" INTEGER;
ALTER TABLE "WARDS" ADD COLUMN IF NOT EXISTS "BRANCH_ID" INTEGER;
ALTER TABLE "WARDS" ADD COLUMN IF NOT EXISTS "DISCONTINUE_FLAG" VARCHAR(10);

