CREATE UNIQUE INDEX IF NOT EXISTS "HR_ATTENDANCE_EMPLOYEE_ID_WORK_DATE_key" ON "HR_ATTENDANCE"("EMPLOYEE_ID", "WORK_DATE");
CREATE INDEX IF NOT EXISTS "HR_ATTENDANCE_WORK_DATE_idx" ON "HR_ATTENDANCE"("WORK_DATE");
CREATE INDEX IF NOT EXISTS "HR_ATTENDANCE_STATUS_idx" ON "HR_ATTENDANCE"("STATUS");

CREATE TABLE IF NOT EXISTS "HR_LEAVE_REQUESTS" (
