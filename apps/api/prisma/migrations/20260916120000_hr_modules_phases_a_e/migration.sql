CREATE TABLE IF NOT EXISTS "HR_PAYROLL_LINES" (
    "LINE_ID" SERIAL NOT NULL,
    "RUN_ID" INTEGER NOT NULL,
    "EMPLOYEE_ID" INTEGER NOT NULL,
    "BASIC" DECIMAL(14,2) NOT NULL DEFAULT 0,
    "ALLOWANCES" DECIMAL(14,2) NOT NULL DEFAULT 0,
    "DEDUCTIONS" DECIMAL(14,2) NOT NULL DEFAULT 0,
    "PAYE" DECIMAL(14,2) NOT NULL DEFAULT 0,
    "PENSION" DECIMAL(14,2) NOT NULL DEFAULT 0,
    "NET_PAY" DECIMAL(14,2) NOT NULL DEFAULT 0,
    "STATUS" VARCHAR(20) NOT NULL DEFAULT 'Pending',
    CONSTRAINT "HR_PAYROLL_LINES_pkey" PRIMARY KEY ("LINE_ID"),
    CONSTRAINT "HR_PAYROLL_LINES_RUN_ID_fkey" FOREIGN KEY ("RUN_ID") REFERENCES "HR_PAYROLL_RUNS"("RUN_ID") ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT "HR_PAYROLL_LINES_EMPLOYEE_ID_fkey" FOREIGN KEY ("EMPLOYEE_ID") REFERENCES "HR_EMPLOYEES"("EMPLOYEE_ID") ON DELETE RESTRICT ON UPDATE CASCADE
