-- HR modules Phases B–E (employees, attendance, leave, performance, payroll)

CREATE TABLE IF NOT EXISTS "HR_EMPLOYEES" (
    "EMPLOYEE_ID" SERIAL NOT NULL,
    "EMPLOYEE_NO" VARCHAR(40) NOT NULL,
    "USER_ID" INTEGER,
    "FIRST_NAME" VARCHAR(100) NOT NULL,
    "LAST_NAME" VARCHAR(100) NOT NULL,
    "EMAIL" VARCHAR(255),
    "PHONE" VARCHAR(50),
    "DEPARTMENT_ID" INTEGER,
    "DEPARTMENT_NAME" VARCHAR(150),
    "DESIGNATION" VARCHAR(150),
    "GRADE_LEVEL" VARCHAR(50),
    "CADRE" VARCHAR(100),
    "EMPLOYMENT_TYPE" VARCHAR(30) NOT NULL DEFAULT 'Permanent',
    "STATUS" VARCHAR(30) NOT NULL DEFAULT 'Active',
    "DATE_JOINED" DATE,
    "DATE_OF_BIRTH" DATE,
    "EXPECTED_RETIRE_DATE" DATE,
    "DATE_LEFT" DATE,
    "QUALIFICATIONS" TEXT,
    "CERTIFICATIONS" TEXT,
    "LICENSE_NO" VARCHAR(100),
    "LICENSE_EXPIRY" DATE,
    "NEXT_OF_KIN" VARCHAR(255),
    "NEXT_OF_KIN_PHONE" VARCHAR(50),
    "EMERGENCY_CONTACT" VARCHAR(255),
    "EMERGENCY_PHONE" VARCHAR(50),
    "EMPLOYMENT_HISTORY" TEXT,
    "BASE_SALARY" DECIMAL(14,2),
    "CREATED_BY_ID" INTEGER,
    "CREATED_BY" VARCHAR(100),
    "CREATED_DATE" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "UPDATED_BY_ID" INTEGER,
    "UPDATED_BY" VARCHAR(100),
    "UPDATED_DATE" TIMESTAMP(3),
    CONSTRAINT "HR_EMPLOYEES_pkey" PRIMARY KEY ("EMPLOYEE_ID")
);

CREATE UNIQUE INDEX IF NOT EXISTS "HR_EMPLOYEES_EMPLOYEE_NO_key" ON "HR_EMPLOYEES"("EMPLOYEE_NO");
CREATE UNIQUE INDEX IF NOT EXISTS "HR_EMPLOYEES_USER_ID_key" ON "HR_EMPLOYEES"("USER_ID");
CREATE INDEX IF NOT EXISTS "HR_EMPLOYEES_STATUS_idx" ON "HR_EMPLOYEES"("STATUS");
CREATE INDEX IF NOT EXISTS "HR_EMPLOYEES_DEPARTMENT_ID_idx" ON "HR_EMPLOYEES"("DEPARTMENT_ID");
CREATE INDEX IF NOT EXISTS "HR_EMPLOYEES_EMPLOYMENT_TYPE_idx" ON "HR_EMPLOYEES"("EMPLOYMENT_TYPE");
CREATE INDEX IF NOT EXISTS "HR_EMPLOYEES_DEPARTMENT_NAME_idx" ON "HR_EMPLOYEES"("DEPARTMENT_NAME");

CREATE TABLE IF NOT EXISTS "HR_LEAVE_TYPES" (
    "LEAVE_TYPE_ID" SERIAL NOT NULL,
    "CODE" VARCHAR(40) NOT NULL,
    "NAME" VARCHAR(100) NOT NULL,
    "DAYS_PER_YEAR" INTEGER NOT NULL DEFAULT 0,
    "IS_ACTIVE" BOOLEAN NOT NULL DEFAULT true,
    CONSTRAINT "HR_LEAVE_TYPES_pkey" PRIMARY KEY ("LEAVE_TYPE_ID")
);
CREATE UNIQUE INDEX IF NOT EXISTS "HR_LEAVE_TYPES_CODE_key" ON "HR_LEAVE_TYPES"("CODE");

