    CONSTRAINT "HR_LEAVE_REQUESTS_LEAVE_TYPE_ID_fkey" FOREIGN KEY ("LEAVE_TYPE_ID") REFERENCES "HR_LEAVE_TYPES"("LEAVE_TYPE_ID") ON DELETE SET NULL ON UPDATE CASCADE
