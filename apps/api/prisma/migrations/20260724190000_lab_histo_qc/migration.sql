-- Histopathology cases
CREATE TABLE IF NOT EXISTS "LAB_HISTOPATHOLOGY_CASES" (
    "CASE_ID" SERIAL NOT NULL,
    "CASE_NO" VARCHAR(50) NOT NULL,
    "PERSON_ID" INTEGER NOT NULL,
    "LAB_REQUEST_ID" INTEGER,
    "SPECIMEN_TYPE" VARCHAR(80) NOT NULL,
    "STAGE" VARCHAR(40) NOT NULL DEFAULT 'Received',
    "SITE" VARCHAR(255),
    "GROSS" TEXT,
    "MICRO" TEXT,
    "DIAGNOSIS" TEXT,
    "GRADE" VARCHAR(80),
    "RECEIVED_AT" TIMESTAMP(3),
    "CREATED_BY_ID" INTEGER,
    "CREATED_BY" VARCHAR(100),
    "CREATED_DATE" TIMESTAMP(3),
    "UPDATED_BY_ID" INTEGER,
    "UPDATED_BY" VARCHAR(100),
    "UPDATED_DATE" TIMESTAMP(3),
    "DELETED_FLAG" VARCHAR(1) DEFAULT 'N',

    CONSTRAINT "LAB_HISTOPATHOLOGY_CASES_pkey" PRIMARY KEY ("CASE_ID")
);

CREATE UNIQUE INDEX IF NOT EXISTS "LAB_HISTOPATHOLOGY_CASES_CASE_NO_key" ON "LAB_HISTOPATHOLOGY_CASES"("CASE_NO");
CREATE INDEX IF NOT EXISTS "LAB_HISTOPATHOLOGY_CASES_PERSON_ID_idx" ON "LAB_HISTOPATHOLOGY_CASES"("PERSON_ID");
CREATE INDEX IF NOT EXISTS "LAB_HISTOPATHOLOGY_CASES_STAGE_idx" ON "LAB_HISTOPATHOLOGY_CASES"("STAGE");
CREATE INDEX IF NOT EXISTS "LAB_HISTOPATHOLOGY_CASES_CREATED_DATE_idx" ON "LAB_HISTOPATHOLOGY_CASES"("CREATED_DATE");

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'LAB_HISTOPATHOLOGY_CASES_PERSON_ID_fkey'
  ) THEN
    ALTER TABLE "LAB_HISTOPATHOLOGY_CASES"
      ADD CONSTRAINT "LAB_HISTOPATHOLOGY_CASES_PERSON_ID_fkey"
      FOREIGN KEY ("PERSON_ID") REFERENCES "PERSONS"("PERSON_ID")
      ON DELETE RESTRICT ON UPDATE CASCADE;
  END IF;
END $$;

-- Quality control runs
