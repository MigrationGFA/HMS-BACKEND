    "QC_RUN_ID" SERIAL NOT NULL,
    "RUN_NO" VARCHAR(50) NOT NULL,
    "ANALYTE" VARCHAR(150) NOT NULL,
    "INSTRUMENT" VARCHAR(150) NOT NULL,
    "LEVEL" VARCHAR(10) NOT NULL,
    "EXPECTED" VARCHAR(80) NOT NULL,
    "OBSERVED" VARCHAR(80) NOT NULL,
    "RESULT" VARCHAR(20) NOT NULL,
    "FREQ" VARCHAR(40) NOT NULL,
    "RUN_DATE" DATE NOT NULL,
